// Dictionary-only accessors. These do not modify the existing site architecture.
window.DLO_TRANSLATE = function(key, lang, page) {
  lang = lang || 'en';
  if (lang === 'en') return key;
  var pageDict = page && window.DLO_TRANSLATIONS.pages[page];
  var entry = (pageDict && pageDict[key]) || window.DLO_TRANSLATIONS.common[key];
  return entry && entry[lang] ? entry[lang] : key;
};

window.DLO_TRANSLATION_LANGUAGE = function(lang) {
  return window.DLO_TRANSLATIONS.languages[lang] || window.DLO_TRANSLATIONS.languages.en;
};

